"""
Pydantic contracts and data schemas for all 3 stages of the intake pipeline.
Strict validation, serialization, and typing compliant with Pydantic v2.
"""

from __future__ import annotations
from datetime import datetime, timezone
from typing import List, Literal, Optional, Dict, Any
from pydantic import BaseModel, Field, field_validator


# ==============================================================================
# STAGE 1: INGESTION & UNIFIED NORMALIZATION SCHEMAS
# ==============================================================================

class ContactInfo(BaseModel):
    """Normalized contact endpoints across leads and patients."""
    email: Optional[str] = Field(None, description="Primary email address")
    phone: Optional[str] = Field(None, description="Phone number (mobile/home/work)")
    linkedin_url: Optional[str] = Field(None, description="LinkedIn profile or sales navigator URL")
    address: Optional[str] = Field(None, description="Physical residential or office address")
    preferred_channel: Optional[str] = Field(None, description="Inferred or stated communication channel")


class UnifiedRecord(BaseModel):
    """
    Unified canonical representation harmonizing B2B leads and clinical patient records.
    Provides a predictable contract for downstream agent reasoning.
    """
    id: str = Field(..., description="Unique deterministic identifier (e.g. lead_xxx or fhir_xxx)")
    source: Literal["linkedin_csv", "smart_fhir_r4"] = Field(
        ..., description="Data provenance indicating the ingestion origin"
    )
    name: str = Field(..., min_length=1, description="Full recipient name")
    contact_info: ContactInfo = Field(default_factory=ContactInfo)
    context: str = Field(
        ...,
        min_length=5,
        description="Structured domain context (B2B: title, company, bio | Health: age, gender, conditions, visits)"
    )
    priority_signal: str = Field(
        ...,
        description="Extracted high-value heuristic signals indicating urgency, seniority, or risk"
    )
    raw_payload: Dict[str, Any] = Field(
        default_factory=dict,
        description="Unmodified source payload preserved for auditing and data lineage"
    )

    @field_validator("name")
    @classmethod
    def validate_name_not_blank(cls, v: str) -> str:
        clean = v.strip()
        if not clean:
            raise ValueError("Name cannot be empty or whitespace only")
        return clean


class DeadLetterRecord(BaseModel):
    """Schema for records rejected by Stage 1 validation or ingestion errors."""
    record_id: Optional[str] = None
    source: str
    error_reason: str
    raw_data: Dict[str, Any]
    timestamp_utc: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )


# ==============================================================================
# STAGE 2: MULTI-STEP AGENT REASONING SCHEMAS
# ==============================================================================

class Step1Analysis(BaseModel):
    """Step 1 Output: Data Quality Gate and Qualification."""
    completeness_score: float = Field(
        ..., ge=0.0, le=1.0, description="Completeness metric based on valid contact points and context"
    )
    usable_channels: List[str] = Field(
        default_factory=list, description="Available reachable channels (e.g. email, phone, linkedin_dm)"
    )
    classification: Literal[
        "HOT",
        "WARM",
        "COLD",
        "HIGH_CLINICAL_URGENCY",
        "ROUTINE_CARE",
        "DATA_INCOMPLETE"
    ] = Field(..., description="Domain-specific triage qualification")
    qualification_rationale: str = Field(
        ..., min_length=10, description="Step 1 reasoning explaining the classification decision"
    )


class Step2Action(BaseModel):
    """Step 2 Output: Action & Policy Routing."""
    recommended_channel: Literal[
        "email",
        "linkedin_dm",
        "sms",
        "phone_call",
        "clinical_escalation_queue",
        "manual_enrichment_queue"
    ] = Field(..., description="Actionable operational delivery channel")
    tone: Literal[
        "consultative_executive",
        "empathetic_clinical",
        "urgent_care_coordination",
        "professional_concise",
        "administrative_intake"
    ] = Field(..., description="Target communication voice and tone")
    escalate_flag: bool = Field(
        ..., description="True if executive decision maker, high clinical risk, or missing contact data"
    )
    routing_rationale: str = Field(
        ..., min_length=10, description="Step 2 reasoning explaining why this channel and tone were picked"
    )


class Step3Message(BaseModel):
    """Step 3 Output: Message Generation and Guardrail Critique."""
    draft_message: str = Field(..., description="Initial draft generated by LLM")
    guardrail_critique: str = Field(
        ..., description="Self-critique evaluation regarding PHI exposure, claims, and tone compliance"
    )
    guardrail_passed: bool = Field(
        ..., description="True if draft passed compliance check without safety violations"
    )
    refinement_applied: bool = Field(
        False, description="True if draft was revised following guardrail critique feedback"
    )
    final_message: str = Field(
        ..., min_length=10, description="Final approved message payload ready for delivery"
    )
    generation_rationale: str = Field(
        ..., min_length=10, description="Step 3 reasoning summarizing generation and safety review"
    )


class AgentReasoningTrace(BaseModel):
    """Complete transparent reasoning trace combining Steps 1, 2, and 3."""
    step1_qualification: Step1Analysis
    step2_action_plan: Step2Action
    step3_message_result: Step3Message
    reasoning_summary: str = Field(
        ..., description="Executive synthesized overview of the agentic decision sequence"
    )


# ==============================================================================
# STAGE 3: DOWNSTREAM CMS/CRM DELIVERY SCHEMAS
# ==============================================================================

class ActionPlan(BaseModel):
    """Structured action metadata attached to the outbound payload."""
    channel: str
    tone: str
    escalate_flag: bool


class DownstreamCMSPayload(BaseModel):
    """
    Strict outbound contract sent to the Mock CMS receiver (POST /api/v1/cms/records).
    Maintains clean boundaries, strict typing, and full traceability.
    """
    delivery_id: str = Field(..., description="Unique UUID for this specific delivery transaction")
    timestamp_utc: str = Field(..., description="ISO 8601 UTC timestamp of dispatch")
    record_id: str = Field(..., description="Canonical ID from UnifiedRecord")
    source_system: str = Field(..., description="linkedin_csv or smart_fhir_r4")
    recipient_name: str = Field(..., description="Full recipient name")
    contact_details: ContactInfo = Field(..., description="Contact channels for dispatch")
    classification: str = Field(..., description="HOT, HIGH_CLINICAL_URGENCY, etc.")
    action_plan: ActionPlan = Field(..., description="Channel, tone, and escalation flag")
    personalized_message: str = Field(..., description="Safe, tailored message or clinical outreach note")
    agent_reasoning_trace: AgentReasoningTrace = Field(
        ..., description="Complete multi-step reasoning trace explaining every decision"
    )
    schema_version: str = Field("1.0.0", description="Contract schema version for forward compatibility")


class CMSReceipt(BaseModel):
    """Downstream acknowledgment confirming ingestion into CMS."""
    cms_receipt_id: str
    status: Literal["accepted", "rejected"]
    received_at: str
    record_id: str
    message: str
